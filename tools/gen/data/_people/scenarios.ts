// The seven eras (剧本). Each nation lists its cities and the generals serving
// in them; every other general who is alive and of age shows up free (在野) in
// a city (his home, unless `free` says otherwise). `hidden` keeps a general off
// the map (e.g. heroes who arrive through a historical event).
//
// Flags are fixed per house so colours stay recognisable across eras:
//  1 孙 2 曹 3 刘备 4 黄巾/黑山 5 董卓/李傕 6 刘焉/刘璋 7 刘表 8 袁术 9 吕布/孟获
//  10 陶谦/刘繇 11 丁原/孔融/轲比能 12 杨奉 13 马腾/羌 14 袁绍 15 公孙瓒
//  16 士燮 17 张鲁 18 公孙氏/张绣/严白虎 (何进 uses 9 in 184)
// BGM 7..9 → strategy themes ad001..ad003.

export interface NationSpec {
  lord: string;
  flag: number;
  bgm: number;
  /** city → serving generals (space separated; the lord is added to his first city if missing) */
  cities: Record<string, string>;
}
export interface ScenarioSpec {
  name: string;
  year: number;
  month: number;
  emperor: number;
  emperorCity: string;
  nations: NationSpec[];
  hidden?: string[];
  /** general → city for free generals not at home */
  free?: Record<string, string>;
  /** friendship overrides: 'A|B' → value (symmetric); default 50 */
  friends?: Record<string, number>;
}

