// Historical events (Event / EventCond / EventMsg). Dialogue is our own.
// Condition types understood by src/game/events.ts checkCond:
//   1 AND(a,b) 2 OR(a,b) 4 general a in city b 6 a (and b) are ruling lords
//   7 a and b serve the same nation 8 lord a holds city b 9 lord a borders/allied lord b
//   10 event a fired 12 NOT(a)
// Event ids 2, 10, 12, 27, 31 carry hard-coded effects in the runtime
// (桃园结义 / 美人计 / 陶谦让徐州 / 三顾茅庐 / 孙刘联姻) and keep those meanings.
import type { IniSection } from '../../types.ts';

type C = number;
const conds: IniSection[] = [];
let condId = 0;
const mk = (type: number, a: string | number, b: string | number = ''): C => {
  const id = ++condId;
  conds.push({ _: 'Condition', ID: String(id), Type: String(type), Param: [String(a), String(b)] });
  return id;
};
const and = (...cs: C[]): C => cs.reduce((x, y) => mk(1, x, y));
const or = (...cs: C[]): C => cs.reduce((x, y) => mk(2, x, y));
const lords = (a: string, b = '') => mk(6, a, b);
const same = (a: string, b: string) => mk(7, a, b);
const holds = (lord: string, city: string) => mk(8, lord, city);
const borders = (a: string, b: string) => mk(9, a, b);
const fired = (e: number) => mk(10, e);
const not = (c: C) => mk(12, c);

const msgs: IniSection[] = [];
let msgId = 0;
/** lines: [speaker ('' = narration), text] → id of the first message */
function say(lines: [string, string][]): number {
  const first = msgId + 1;
  lines.forEach(([name, text], i) => {
    const id = ++msgId;
    msgs.push({ _: 'EventMsg', ID: String(id), ...(name ? { Name: name } : {}), Text: text, Next: i + 1 < lines.length ? String(id + 1) : '' });
  });
  return first;
}

