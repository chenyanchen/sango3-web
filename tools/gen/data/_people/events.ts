let built: Record<string, IniSection[]> | null = null;
export function eventFiles(): Record<string, IniSection[]> {
  if (built) return built;
  const ev: IniSection[] = EVENTS.map((e) => ({
    _: 'Event', ID: String(e.id), Name: e.name, Year: String(e.year), Month: String(e.month),
    Condition: e.cond ? String(e.cond) : '', Msg: String(say(e.lines)),
  }));
  built = { Event: ev, EventCond: [...conds], EventMsg: [...msgs] };
  return built;
}

