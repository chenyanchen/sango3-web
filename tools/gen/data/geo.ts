/** Map projection: the playable area of China onto the 1024×768 strategy map (with margins). */
export const MAP_W = 1024;
export const MAP_H = 768;
const LON0 = 100.0, LON1 = 125.6, LAT0 = 19.6, LAT1 = 42.6;
export function project(lon: number, lat: number): [number, number] {
  return [((lon - LON0) / (LON1 - LON0)) * MAP_W, ((LAT1 - lat) / (LAT1 - LAT0)) * MAP_H];
}
export function unproject(x: number, y: number): [number, number] {
  return [LON0 + (x / MAP_W) * (LON1 - LON0), LAT1 - (y / MAP_H) * (LAT1 - LAT0)];
}

/** Small pixel nudges so neighbouring city icons don't overlap. */
// prettier-ignore
const NUDGE: Record<string, [number, number]> = {
  河内: [-12, -10], 虎牢关: [10, 7], 小沛: [-8, -10], 彭城: [6, 8], 宛: [2, -10], 新野: [-9, 2], 襄阳: [6, 9], 剑阁: [8, -7], 梓潼: [-7, 7],
};

export const CITIES: City[] = ROWS.map(([name, size, lon, lat, region, terrain], i) => {
  const p = project(lon, lat);
  const [x, y] = [p[0] + (NUDGE[name]?.[0] ?? 0), p[1] + (NUDGE[name]?.[1] ?? 0)];
  const snow: City['snow'] = lat >= 37 ? 2 : lat >= 33 ? 1 : 0;
  return { id: i + 1, name, size, snow, lon, lat, x: Math.round(x), y: Math.round(y), region, terrain };
});

export const CITY = new Map(CITIES.map((c) => [c.name, c]));

export const NEIGHBORS: Map<string, string[]> = (() => {
  const m = new Map<string, string[]>(CITIES.map((c) => [c.name, []]));
  for (const [a, b] of EDGES) {
    if (!m.has(a) || !m.has(b)) throw new Error(`geo: unknown city in edge ${a}-${b}`);
    m.get(a)!.push(b);
    m.get(b)!.push(a);
  }
  return m;
})();

