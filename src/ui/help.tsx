export function showHelp(): Promise<void> {
  return modal<void>((close) => <Help close={close} />);
}

function Help(props: { close: () => void }) {
  const [tab, setTab] = useState(0);
  const s = SECTIONS[tab];
  return (
    <Panel title="游戏说明" class="modal" style={{ width: 'min(46em, 94vw)', height: 'min(34em, 90vh)' }}>
      <div class="tabs" style={{ flexWrap: 'wrap' }}>
        {SECTIONS.map((x, i) => (
          <button class={i === tab ? 'on' : ''} onClick={() => setTab(i)}>
            {x.title}
          </button>
        ))}
      </div>
      <div class="body grow" style={{ lineHeight: 1.85, fontSize: '1.02em' }}>
        {s.body.map((p) => (
          <p style={{ margin: '0 0 0.7em' }}>{p}</p>
        ))}
      </div>
      <div class="actions">
        <Btn class="primary" onClick={props.close}>
          关闭
        </Btn>
      </div>
    </Panel>
  );
}
